"""Model artifact persistence: joblib bundles under ``app/ml/artifacts/``.

Artifacts are generated by ``app.ml.train`` and intentionally NOT committed:
any checkout reproduces them deterministically by retraining on the same
database. Loading a missing artifact raises ``ModelNotTrainedError`` with
the exact command to run — inference never trains as a side effect.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import joblib

ARTIFACTS_DIR = Path(__file__).resolve().parent / "artifacts"

FILENAMES: dict[str, str] = {
    "segmentation": "segmentation.joblib",
    "churn": "churn.joblib",
    "purchase": "purchase.joblib",
}


class ModelNotTrainedError(Exception):
    """Raised when inference is attempted without a persisted artifact."""


def artifact_path(kind: str, directory: Path | None = None) -> Path:
    return (directory or ARTIFACTS_DIR) / FILENAMES[kind]


def save_bundle(kind: str, bundle: dict[str, Any], directory: Path | None = None) -> Path:
    target_dir = directory or ARTIFACTS_DIR
    target_dir.mkdir(parents=True, exist_ok=True)
    path = target_dir / FILENAMES[kind]
    joblib.dump(bundle, path)
    return path


def load_bundle(kind: str, directory: Path | None = None) -> dict[str, Any]:
    path = artifact_path(kind, directory)
    if not path.exists():
        raise ModelNotTrainedError(
            f"No {kind} artifact at {path}. Train first: uv run python -m app.ml.train"
        )
    return joblib.load(path)
