"use client";

import * as React from "react";
import { Sparkle, Sparkles } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { useAiOperation } from "@/hooks/use-ai";
import { postAIInsight, postAISummarize, type AIContextRef } from "@/lib/api";

interface InsightCardProps {
  context: AIContextRef;
  title: string;
  description: string;
  mode?: "insight" | "summary";
  actionLabel?: string;
}

/**
 * Restrained AI explanation embedded in an analytical workflow.
 * Explicit user action starts generation; deterministic page content
 * is never blocked on the model. Provenance is always shown.
 */
export function InsightCard({
  context,
  title,
  description,
  mode = "insight",
  actionLabel,
}: InsightCardProps) {
  const operation = React.useCallback(
    (signal: AbortSignal) =>
      mode === "summary" ? postAISummarize(context, signal) : postAIInsight(context, signal),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [mode, context.kind, context.id],
  );
  const { status, answer, error, run } = useAiOperation(
    operation,
    `${mode}-${context.kind}-${context.id ?? "global"}`,
  );
  const buttonLabel =
    actionLabel ?? (mode === "summary" ? "Summarize" : "Explain this");

  return (
    <Card aria-label={title}>
      <CardHeader>
        <div className="flex flex-wrap items-center justify-between gap-2">
          <CardTitle className="flex items-center gap-2 text-[15px]">
            <Sparkles aria-hidden="true" className="size-4 text-muted-foreground" />
            {title}
          </CardTitle>
          {(status === "idle" || status === "error") && (
            <Button type="button" variant="secondary" size="sm" onClick={run}>
              {status === "error" ? "Try again" : buttonLabel}
            </Button>
          )}
        </div>
      </CardHeader>
      <CardContent>
        {status === "idle" && <p className="text-sm text-muted-foreground">{description}</p>}
        {status === "loading" && (
          <div className="flex flex-col gap-2" role="status" aria-label="Generating explanation">
            <Skeleton className="h-4 w-full" />
            <Skeleton className="h-4 w-11/12" />
            <Skeleton className="h-4 w-4/5" />
            <span className="sr-only">Generating explanation…</span>
          </div>
        )}
        {status === "success" && answer !== null && (
          <div className="flex min-h-0 min-w-0 flex-col gap-2">
            <p className="min-h-0 min-w-0 whitespace-pre-wrap break-words text-sm">{answer.text}</p>
            <p className="flex flex-wrap items-center gap-2 text-meta text-muted-foreground">
              <Badge variant="outline">AI explanation</Badge>
              <span>
                Generated by {answer.model} from verified {answer.context_kind} data.
              </span>
            </p>
          </div>
        )}
        {status === "error" && (
          <div className="flex flex-col gap-2" role="alert">
            <p className="flex items-start gap-2 text-sm">
              <Sparkle aria-hidden="true" className="mt-0.5 size-4 shrink-0 text-muted-foreground" />
              <span>{error ?? "Explanations are unavailable right now."}</span>
            </p>
            <p className="text-meta text-muted-foreground">
              Every metric on this page remains verified backend data.
            </p>
          </div>
        )}
      </CardContent>
    </Card>
  );
}
