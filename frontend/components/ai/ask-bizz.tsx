"use client";

import * as React from "react";
import { MessageCircleQuestion, SendHorizonal } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Skeleton } from "@/components/ui/skeleton";
import { useAiOperation } from "@/hooks/use-ai";
import { postAIAsk, type AIContextRef } from "@/lib/api";

const SUGGESTIONS = [
  "What changed most in this view?",
  "Which signals matter most here?",
  "What should be investigated first?",
];

interface AskBizzProps {
  context: AIContextRef;
  title?: string;
  description?: string;
}

/**
 * Restrained analytical Q&A scoped to one view's verified context.
 * Questions are validated (non-empty, bounded) and answered only from
 * the context the backend assembles — never from model memory.
 */
export function AskBizz({
  context,
  title = "Ask Bizz",
  description = "Ask about exactly what is shown in this view. Answers use only verified backend data.",
}: AskBizzProps) {
  const [question, setQuestion] = React.useState("");
  const [asked, setAsked] = React.useState<string | null>(null);

  const operation = React.useCallback(
    (signal: AbortSignal) => postAIAsk(context, asked ?? "", signal),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [context.kind, context.id, asked],
  );
  const key = `${context.kind}-${context.id ?? "global"}-${asked ?? ""}`;
  const { status, answer, error, run } = useAiOperation(operation, key);

  const submit = (event: React.FormEvent) => {
    event.preventDefault();
    const trimmed = question.trim();
    if (trimmed.length === 0 || trimmed.length > 1000) return;
    setAsked(trimmed);
    run();
  };

  return (
    <Card aria-label={title}>
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-[15px]">
          <MessageCircleQuestion aria-hidden="true" className="size-4 text-muted-foreground" />
          {title}
        </CardTitle>
      </CardHeader>
      <CardContent className="flex flex-col gap-3">
        <p className="text-sm text-muted-foreground">{description}</p>
        <form onSubmit={submit} className="flex gap-2">
          <label htmlFor={`ask-bizz-${key}`} className="sr-only">
            Analytical question
          </label>
          <Input
            id={`ask-bizz-${key}`}
            value={question}
            onChange={(event) => setQuestion(event.target.value)}
            placeholder="e.g. What changed most in this view?"
            maxLength={1000}
            autoComplete="off"
            disabled={status === "loading"}
          />
          <Button
            type="submit"
            variant="secondary"
            disabled={status === "loading" || question.trim().length === 0}
          >
            <SendHorizonal aria-hidden="true" />
            Ask
          </Button>
        </form>
        <div className="flex flex-wrap gap-2" aria-label="Suggested questions">
          {SUGGESTIONS.map((suggestion) => (
            <Button
              key={suggestion}
              type="button"
              variant="ghost"
              size="sm"
              disabled={status === "loading"}
              onClick={() => {
                setQuestion(suggestion);
                setAsked(suggestion);
                run();
              }}
            >
              {suggestion}
            </Button>
          ))}
        </div>
        {status === "loading" && (
          <div className="flex flex-col gap-2" role="status" aria-label="Answering question">
            <Skeleton className="h-4 w-full" />
            <Skeleton className="h-4 w-5/6" />
            <span className="sr-only">Answering question…</span>
          </div>
        )}
        {status === "success" && answer !== null && asked !== null && (
          <div className="flex min-h-0 min-w-0 flex-col gap-2 rounded-md border border-border p-3">
            <p className="min-w-0 break-words text-sm font-medium">Q: {asked}</p>
            <p className="min-h-0 min-w-0 whitespace-pre-wrap break-words text-sm">{answer.text}</p>
            <p className="flex flex-wrap items-center gap-2 text-meta text-muted-foreground">
              <Badge variant="outline">AI answer</Badge>
              <span>
                Generated by {answer.model} from verified {answer.context_kind} data.
              </span>
            </p>
          </div>
        )}
        {status === "error" && (
          <p role="alert" className="text-sm">
            {error ?? "Answers are unavailable right now."}{" "}
            <span className="text-muted-foreground">
              Every metric on this page remains verified backend data.
            </span>
          </p>
        )}
      </CardContent>
    </Card>
  );
}
