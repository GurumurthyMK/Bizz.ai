"use client";

import * as React from "react";
import Link from "next/link";
import { ArrowRight, FileText } from "lucide-react";
import { PageHeader } from "@/components/layout/page-header";
import { ActivityChart, RevenueTrendChart } from "@/components/overview/trend-charts";
import { KpiCard } from "@/components/overview/kpi-card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { EmptyState } from "@/components/ui/empty-state";
import { ErrorState } from "@/components/ui/error-state";
import { Skeleton } from "@/components/ui/skeleton";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { ApiError, generateReport } from "@/lib/api";
import { formatCurrency, formatDate, formatNumber, formatPercent, formatProbability } from "@/lib/format";
import type { BusinessReport } from "@/types";

function priorityVariant(priority: string): "danger" | "warning" | "default" {
  return priority === "high" ? "danger" : priority === "medium" ? "warning" : "default";
}

/** Business report workflow: generate on demand, read grounded sections. */
export function ReportView() {
  const [report, setReport] = React.useState<BusinessReport | null>(null);
  const [loading, setLoading] = React.useState(false);
  const [error, setError] = React.useState<string | null>(null);

  const generate = async () => {
    const controller = new AbortController();
    setLoading(true);
    setError(null);
    try {
      const result = await generateReport(controller.signal);
      setReport(result);
    } catch (fetchError) {
      if (fetchError instanceof ApiError && fetchError.status === 401) {
        setError("Your session expired. Please log in again.");
      } else if (fetchError instanceof Error) {
        setError(`Unable to generate the report: ${fetchError.message}`);
      } else {
        setError("Unable to generate the report.");
      }
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="flex flex-col gap-6">
      <PageHeader
        title="Reports"
        description="On-demand business reports over verified data, with optional AI narrative."
        actions={
          <Button type="button" onClick={generate} disabled={loading}>
            <FileText aria-hidden="true" />
            {loading ? "Generating…" : report === null ? "Generate report" : "Regenerate"}
          </Button>
        }
      />

      {loading ? (
        <div className="flex flex-col gap-3" role="status" aria-label="Generating report">
          <Skeleton className="h-32" />
          <Skeleton className="h-48" />
          <Skeleton className="h-32" />
          <span className="sr-only">Generating report…</span>
        </div>
      ) : error !== null ? (
        <ErrorState title="Report generation failed" description={error} onRetry={generate} />
      ) : report === null ? (
        <EmptyState
          title="No report yet"
          description="Generate a report to assemble executive summary, metrics, trends, segments, predictions, opportunities, and recommendations from current backend data."
          actionLabel="Generate report"
          onAction={generate}
        />
      ) : (
        <>
          <section aria-labelledby="report-summary" className="flex flex-col gap-2">
            <h2 id="report-summary" className="text-section-title">
              Executive summary
            </h2>
            <p className="text-sm">{report.executive_summary}</p>
            {report.narrative.executive_summary !== null ? (
              <div className="flex flex-col gap-1 rounded-lg border bg-card p-4">
                <p className="whitespace-pre-line text-sm">{report.narrative.executive_summary}</p>
                <p className="text-meta text-muted-foreground">
                  <Badge variant="outline">AI narrative</Badge> Generated by{" "}
                  {report.narrative.model} from this report&apos;s verified facts.
                </p>
              </div>
            ) : (
              <p className="text-meta text-muted-foreground">
                AI narrative unavailable — all sections below remain verified backend data.
              </p>
            )}
            <p className="text-meta text-muted-foreground">
              Reference {formatDate(report.meta.reference_date)} ·{" "}
              {formatNumber(report.meta.customer_count)} customers on record.
            </p>
          </section>

          <section aria-labelledby="report-metrics" className="flex flex-col gap-3">
            <h2 id="report-metrics" className="text-section-title">
              Key metrics
            </h2>
            <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 xl:grid-cols-4">
              <KpiCard kpi={report.key_metrics.revenue} formatValue={formatCurrency} />
              <KpiCard kpi={report.key_metrics.active_customers} formatValue={formatNumber} />
              <KpiCard kpi={report.key_metrics.transactions} formatValue={formatNumber} />
              <KpiCard
                kpi={report.key_metrics.avg_order_value}
                formatValue={formatCurrency}
                context="per completed order"
              />
            </div>
          </section>

          <section aria-labelledby="report-trends" className="flex flex-col gap-3">
            <h2 id="report-trends" className="text-section-title">
              Customer trends
            </h2>
            <div className="grid grid-cols-1 gap-3 xl:grid-cols-2">
              <RevenueTrendChart trends={report.customer_trends} />
              <ActivityChart trends={report.customer_trends} />
            </div>
          </section>

          <section aria-labelledby="report-segments" className="flex flex-col gap-3">
            <h2 id="report-segments" className="text-section-title">
              Segment analysis
            </h2>
            {report.segments.length === 0 ? (
              <EmptyState
                title="No segments in this report"
                description="Segment output has not been materialized for the reference period."
              />
            ) : (
              <Table aria-label="Report segments">
                <TableHeader>
                  <TableRow>
                    <TableHead>Segment</TableHead>
                    <TableHead className="text-right">Customers</TableHead>
                    <TableHead className="text-right">Avg revenue</TableHead>
                    <TableHead className="text-right">Avg recency</TableHead>
                    <TableHead>
                      <span className="sr-only">Open</span>
                    </TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {report.segments.map((segment) => (
                    <TableRow key={segment.id}>
                      <TableCell>
                        <Link
                          href={`/segments/${segment.id}`}
                          className="font-medium underline-offset-4 hover:underline"
                        >
                          {segment.name}
                        </Link>
                      </TableCell>
                      <TableCell className="text-right tabular-nums">
                        {formatNumber(segment.size)}
                      </TableCell>
                      <TableCell className="text-right tabular-nums">
                        {formatCurrency(segment.avg_revenue)}
                      </TableCell>
                      <TableCell className="text-right tabular-nums">
                        {Math.round(segment.avg_recency_days)} days
                      </TableCell>
                      <TableCell className="text-right">
                        <Button variant="ghost" size="sm" asChild>
                          <Link href={`/segments/${segment.id}`} aria-label={`Open ${segment.name}`}>
                            <ArrowRight aria-hidden="true" />
                          </Link>
                        </Button>
                      </TableCell>
                    </TableRow>
                  ))}
                </TableBody>
              </Table>
            )}
          </section>

          <section aria-labelledby="report-predictions" className="flex flex-col gap-3">
            <h2 id="report-predictions" className="text-section-title">
              Predictions
            </h2>
            <p className="text-sm text-muted-foreground">
              {formatNumber(report.predictions.churn_high_count)} high churn-risk customers ·{" "}
              {formatNumber(report.predictions.purchase_high_count)} high purchase-likelihood
              customers.
            </p>
            <div className="grid grid-cols-1 gap-3 lg:grid-cols-2">
              {(
                [
                  { title: "Top churn risk", items: report.predictions.top_churn },
                  { title: "Top purchase likelihood", items: report.predictions.top_purchase },
                ] as const
              ).map((block) => (
                <div key={block.title} className="flex flex-col gap-2">
                  <h3 className="text-sm font-medium">{block.title}</h3>
                  {block.items.length === 0 ? (
                    <p className="text-sm text-muted-foreground">None recorded.</p>
                  ) : (
                    <Table aria-label={block.title}>
                      <TableHeader>
                        <TableRow>
                          <TableHead>Customer</TableHead>
                          <TableHead className="text-right">Probability</TableHead>
                        </TableRow>
                      </TableHeader>
                      <TableBody>
                        {block.items.map((prediction) => (
                          <TableRow key={prediction.id}>
                            <TableCell>
                              <Link
                                href={`/customers/${prediction.customer_id}`}
                                className="font-medium underline-offset-4 hover:underline"
                              >
                                #{prediction.customer_id}
                              </Link>
                            </TableCell>
                            <TableCell className="text-right tabular-nums">
                              {formatProbability(prediction.probability)}
                            </TableCell>
                          </TableRow>
                        ))}
                      </TableBody>
                    </Table>
                  )}
                </div>
              ))}
            </div>
            <div>
              <Button variant="secondary" size="sm" asChild>
                <Link href="/predictions">
                  All predictions
                  <ArrowRight aria-hidden="true" />
                </Link>
              </Button>
            </div>
          </section>

          <section aria-labelledby="report-opportunities" className="flex flex-col gap-3">
            <h2 id="report-opportunities" className="text-section-title">
              Opportunities
            </h2>
            <p className="text-sm text-muted-foreground">
              {formatNumber(report.opportunities.total)} open ·{" "}
              {formatNumber(report.opportunities.high_count)} high tier.
            </p>
            {report.opportunities.top.length === 0 ? (
              <EmptyState
                title="No open opportunities"
                description="No scored opportunities exist for the reference period."
              />
            ) : (
              <Table aria-label="Top report opportunities">
                <TableHeader>
                  <TableRow>
                    <TableHead>Customer</TableHead>
                    <TableHead>Type</TableHead>
                    <TableHead className="text-right">Score</TableHead>
                    <TableHead className="text-right">Est. value</TableHead>
                    <TableHead>
                      <span className="sr-only">Open</span>
                    </TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {report.opportunities.top.map((opp) => (
                    <TableRow key={opp.id}>
                      <TableCell>
                        <Link
                          href={`/customers/${opp.customer_id}`}
                          className="font-medium underline-offset-4 hover:underline"
                        >
                          #{opp.customer_id}
                        </Link>
                      </TableCell>
                      <TableCell className="capitalize">
                        {opp.opportunity_type.replace(/_/g, " ")}
                      </TableCell>
                      <TableCell className="text-right tabular-nums">
                        {formatPercent(opp.score)}
                      </TableCell>
                      <TableCell className="text-right tabular-nums">
                        {formatCurrency(opp.estimated_value)}
                      </TableCell>
                      <TableCell className="text-right">
                        <Button variant="ghost" size="sm" asChild>
                          <Link href={`/opportunities/${opp.id}`} aria-label={`Open opportunity ${opp.id}`}>
                            <ArrowRight aria-hidden="true" />
                          </Link>
                        </Button>
                      </TableCell>
                    </TableRow>
                  ))}
                </TableBody>
              </Table>
            )}
            <div>
              <Button variant="secondary" size="sm" asChild>
                <Link href="/opportunities">
                  All opportunities
                  <ArrowRight aria-hidden="true" />
                </Link>
              </Button>
            </div>
          </section>

          <section aria-labelledby="report-recommendations" className="flex flex-col gap-3">
            <h2 id="report-recommendations" className="text-section-title">
              Recommendations
            </h2>
            {report.recommendations.length === 0 ? (
              <EmptyState
                title="No recommendations"
                description="Current conditions produced no prioritized actions."
              />
            ) : (
              <ol className="flex flex-col gap-2">
                {report.recommendations.map((item) => (
                  <li key={item.title} className="rounded-lg border bg-card p-4">
                    <p className="flex flex-wrap items-center gap-2 text-sm font-medium">
                      <Badge variant={priorityVariant(item.priority)}>{item.priority}</Badge>
                      {item.title}
                    </p>
                    <p className="mt-1 text-sm text-muted-foreground">{item.detail}</p>
                  </li>
                ))}
              </ol>
            )}
            {report.narrative.recommendations !== null && (
              <div className="flex flex-col gap-1 rounded-lg border bg-card p-4">
                <p className="whitespace-pre-line text-sm">{report.narrative.recommendations}</p>
                <p className="text-meta text-muted-foreground">
                  <Badge variant="outline">AI narrative</Badge> Generated by{" "}
                  {report.narrative.model} from this report&apos;s verified facts.
                </p>
              </div>
            )}
          </section>
        </>
      )}
    </div>
  );
}
